"""results_vqa.json -> RESULTS_raw.md (all tables) + plots/seq_<ds>.png (Overall F1 vs average samples)."""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
R = json.load(open(f"{HERE}/results_vqa.json"))
NAMES = {"uvqa": "UVQA", "unkvqa": "UNK-VQA", "spatialuncertain": "SpatialUncertain"}
E1_SHOW = ["self Consistency", "Majority", "self Consistency + T", "scUn", "CRP_k", "CRP_theta",
           "Adaptive_Consistency_beta", "TwoRest_CRP", "TwoRest_Reserved_CRP", "TwoRest_Hurdle_CRP",
           "TwoRest_ZI_PYP", "Oracle_Intermediate__keepIDK", "Oracle_Intermediate__dropIDK"]
f = lambda x: "–" if x is None else f"{x:.1f}"
g = lambda x: "–" if x is None or x != x else f"{x:.2f}"


def main():
    md = ["# VQA CRP experiments: all tables (generated by make_report.py)", "",
          "Qwen3.8-27B, answerability-aware prompts, 20 samples/q. Test numbers unless marked dev. %.", ""]
    md += ["## E1: experiments_CRP.py pipeline on VQA (test)", ""]
    hdr = "| method | " + " | ".join(f"{NAMES[d]} F1 | A | U | ans% | dev F1" for d in R) + " |"
    md += [hdr, "|---|" + "---|" * (5 * len(R))]
    for m in E1_SHOW:
        cells = []
        for d in R:
            r = R[d]["E1"].get(m)
            cells += [f(r["f1"]), f(r["A_acc"]), f(r["U_acc"]), f(r["answered"]), f(r["dev_f1"])] if r else ["–"] * 5
        md.append(f"| {m} | " + " | ".join(cells) + " |")
    md += ["", "Grid (experiments_CRP RUN_ALL_16_ABLATION_COMBOS) best test cell per method, for reference only "
           "(selecting it would be test-tuning):", ""]
    for d in R:
        best = {}
        for k, v in R[d]["E1"].items():
            if "__V_" in k:
                b = k.split("__")[0]
                if b not in best or v["f1"] > best[b][1]["f1"]:
                    best[b] = (k, v)
        md.append(f"- {NAMES[d]}: " + "; ".join(f"{b} {v['f1']:.1f} (default {R[d]['E1'][b]['f1']:.1f})" for b, (k, v) in best.items()))
    md += ["", "Learned parameters (dev):", ""]
    for d in R:
        for k in ("TwoRest_Hurdle_CRP", "TwoRest_ZI_PYP"):
            p = R[d]["E1_params"].get(k)
            if p:
                md.append(f"- {NAMES[d]} {k}: " + ", ".join(f"{a}={b:.3g}" for a, b in p.items() if a != "method"))
    md += ["", "## E2: sequential stopping (test, averaged over 10 sample orders)", "",
           "Each row = the dev-selected setting with dev average samples <= budget. SPRT stops when the LLR crosses an upper "
           "(abstain) or lower (answer) bound; at 20 samples it falls back to the 20-sample threshold.", ""]
    for d in R:
        E2 = R[d]["E2"]
        md += [f"### {NAMES[d]}", "", "| budget | " + " | ".join(f"{k} F1 (avg n)" for k in ("SPRT hurdle", "SPRT IDK-only", "Adaptive Consistency")) + " |",
               "|---|---|---|---|"]
        for i, b in enumerate(E2["SPRT hurdle"]):
            cells = []
            for k in ("SPRT hurdle", "SPRT IDK-only", "Adaptive Consistency"):
                r = E2[k][i]
                cells.append("–" if r is None else f"{r['f1']:.1f} ({r['avg_t']:.1f})")
            md.append(f"| ≤{b['budget'] if b else '?'} | " + " | ".join(cells) + " |")
        md += ["", "| fixed n | " + " | ".join(f"{k} F1" for k in ("Unans votes", "CRP_k", "Hurdle LLR")) + " |", "|---|---|---|---|"]
        for i, r0 in enumerate(E2["fixed-n Unans votes"]):
            md.append(f"| {r0['n']} | " + " | ".join(f(E2[f'fixed-n {k}'][i]['f1']) for k in ("Unans votes", "CRP_k", "Hurdle LLR")) + " |")
        md += ["", f"Check: SPRT with no early bounds, original order = {E2['_check_hurdle20_perm0']['f1']:.1f} "
               f"(E1 TwoRest_Hurdle_CRP {R[d]['E1']['TwoRest_Hurdle_CRP']['f1']:.1f})", ""]
    md += ["## E3: evenness (sum_k log n_k) at fixed K, dev — what the Pitman-Yor discount could use", "",
           "AUROC for unanswerable (0.5 = no signal); #Unanswerable votes at the same K shown for contrast.", ""]
    for d in R:
        for mode, rows in R[d]["E3"].items():
            md.append(f"- {NAMES[d]}, {mode}: " + "; ".join(
                f"{r['group']} (n={r['n']}, U={r['n_unans']}) evenness {g(r['auroc_evenness'])} vs #IDK {g(r['auroc_n_unans'])}" for r in rows))
    md += ["", "## E4: hard vs unanswerable, dev", "",
           "easy = answerable & self-consistency answer correct; hard = answerable & SC answer wrong or abstained. AUROC with "
           "the first group positive.", ""]
    for d in R:
        E4 = R[d]["E4"]; c = E4["counts"]
        md += [f"### {NAMES[d]} (easy {c['easy']}, hard {c['hard']} of which SC abstained {E4['hard_sc_abstained']}, unans {c['unans']})", "",
               "| signal | unans vs hard | unans vs easy | hard vs easy |", "|---|---|---|---|"]
        for s, v in E4["signals"].items():
            md.append(f"| {s} | {g(v['unans vs hard'])} | {g(v['unans vs easy'])} | {g(v['hard vs easy'])} |")
        md.append("")
    md += ["## E5: Colab hierarchical CRP fitted to the real samples, dev", "",
           "| dataset | alpha MLE A mean (sd) | alpha MLE U mean (sd) | fitted prior A | fitted prior U | AUROC posterior | AUROC K |",
           "|---|---|---|---|---|---|---|"]
    for d in R:
        e = R[d]["E5"]
        md.append(f"| {NAMES[d]} | {e['alpha_mle_A'][0]:.2f} ({e['alpha_mle_A'][1]:.2f}) | {e['alpha_mle_U'][0]:.2f} ({e['alpha_mle_U'][1]:.2f}) | "
                  f"N({e['fitted_prior_A'][0]:.2f}, {e['fitted_prior_A'][1]:.2f}) | N({e['fitted_prior_U'][0]:.2f}, {e['fitted_prior_U'][1]:.2f}) | "
                  f"{g(e['auroc_posterior'])} | {g(e['auroc_K'])} |")
    open(f"{HERE}/RESULTS_raw.md", "w").write("\n".join(md) + "\n")

    try:
        import matplotlib; matplotlib.use("Agg"); import matplotlib.pyplot as plt
    except ImportError:
        return
    os.makedirs(f"{HERE}/plots", exist_ok=True)
    fig, axes = plt.subplots(1, len(R), figsize=(5 * len(R), 4))
    for ax, d in zip(axes, R):
        E2 = R[d]["E2"]
        for k, mk in (("SPRT hurdle", "o-"), ("SPRT IDK-only", "s-"), ("Adaptive Consistency", "^-")):
            pts = sorted({(r["avg_t"], r["f1"]) for r in E2[k] if r})
            ax.plot([p[0] for p in pts], [p[1] for p in pts], mk, label=k, ms=4)
        for k, mk in (("fixed-n Unans votes", "--"), ("fixed-n Hurdle LLR", ":")):
            ax.plot([r["n"] for r in E2[k]], [r["f1"] for r in E2[k]], mk, label=k)
        ax.set_xscale("log"); ax.set_xticks([1, 2, 3, 5, 10, 20]); ax.set_xticklabels(["1", "2", "3", "5", "10", "20"])
        ax.set_xlabel("average samples used"); ax.set_ylabel("test Overall F1 (%)"); ax.set_title(NAMES[d]); ax.grid(alpha=.3)
    axes[0].legend(fontsize=7)
    fig.tight_layout(); fig.savefig(f"{HERE}/plots/sequential.png", dpi=120)


if __name__ == "__main__":
    main()
