"""Reserved-tables restaurant model (designed from the dev distribution audit, final_audit.py).

Per question the 20 samples are reduced to
  n0 = IDK / NK samples, e = empty query results (KBQA only), r = real (non-empty) answers in clusters n_1..n_K,
  L  = number of possible real answers (2 Yes/No, 3-4 MCQ; None = free-form).
Per class y in {A, U} the samples are generated by a mixture of J components; each component has
  composition  (n0, r) ~ Beta-Binomial(a, b)                       non-KBQA: 2 parameters
               (n0, e, r) ~ Dirichlet-Multinomial(a0, ae, ar)      KBQA:     3 parameters
  partition    free-form: CRP(theta)  (EPPF, the prod (n_k-1)! factor is class-independent and dropped)
               L options: symmetric Dirichlet-Multinomial urn with total beta over L options      1 parameter
plus J-1 mixture weights per class (EM, a few restarts). Score = log p(x|U) - log p(x|A); abstain if score > tau.
If not abstaining, answer the largest real (non-IDK, non-empty) cluster; with no real answer -> abstain.

Ablation ladder (all with the same decision and metric code):
  RT0  = Hurdle_CRP equivalent: Beta-Binomial IDK + CRP, empty treated as an ordinary answer cluster in the likelihood
  RT1  = RT0 + option-aware urn for Yes/No and MCQ
  RT2  = RT1 + empty table (KBQA; same as RT1 elsewhere)
  RT3  = RT2 with J = 2 components per class
  RTcv = RT2 or RT3, chosen per dataset by 5-fold CV inside dev
Baselines: SC (majority incl. IDK/empty as abstain options), CRP_k (tuned), LogReg on (n0/N, e/N, c, K).
"""
import numpy as np
from scipy.special import gammaln
from scipy.optimize import minimize


# ---------- per-question features ----------
def featurise(item, mod, L, kbqa):
    """-> dict with n0, e, r, sizes (real clusters), L, answer correctness of the largest real cluster."""
    N, n0, m, clusters, is_corr = mod.extract_clusters(item, ignore_idk=True)[:5]
    emp = [c for c in clusters if all(str(item["pred_answer"][i]).strip() == "" for i in c)] if kbqa else []
    real = [c for c in clusters if c not in emp]
    e = sum(len(c) for c in emp)
    sizes = sorted((len(c) for c in real), reverse=True)
    top = max(real, key=len) if real else None
    return dict(N=N, n0=n0, e=e, r=sum(sizes), sizes=sizes, L=L, kbqa=kbqa,
                top_ok=bool(top) and bool(is_corr[top[0]]),
                # RT0 view: empty is just another cluster of the substantive samples
                sizes_e=sorted([len(c) for c in clusters], reverse=True), m=m,
                # for SC / CRP_k: all outcome groups incl. IDK and empty
                n_groups=len(clusters) + (n0 > 0))


# ---------- component log-likelihoods ----------
def ll_bb(n0, n, a, b):
    return gammaln(n0 + a) + gammaln(n - n0 + b) - gammaln(n + a + b) - (gammaln(a) + gammaln(b) - gammaln(a + b))


def ll_dm(counts, alphas):
    A = alphas.sum()
    return gammaln(A) - gammaln(counts.sum() + A) + np.sum(gammaln(counts + alphas) - gammaln(alphas))


def ll_crp(sizes, theta):
    m = sum(sizes)
    if m == 0:
        return 0.0
    return len(sizes) * np.log(theta) + gammaln(theta) - gammaln(theta + m)


def ll_urn(sizes, beta, L):
    m = sum(sizes)
    if m == 0:
        return 0.0
    a = beta / L
    return gammaln(beta) - gammaln(beta + m) + np.sum(gammaln(np.array(sizes, float) + a) - gammaln(a))


class Spec:
    def __init__(self, urn=True, empty_table=True, J=1):
        self.urn, self.empty_table, self.J = urn, empty_table, J

    def n_comp_params(self, kbqa):
        return (3 if (kbqa and self.empty_table) else 2) + 1

    def comp_ll(self, x, p):
        """p = log-parameters of one component."""
        p = np.exp(p)
        if x["kbqa"] and self.empty_table:
            ll = ll_dm(np.array([x["n0"], x["e"], x["r"]], float), p[:3])
            sizes, part = x["sizes"], p[3]
        else:
            ll = ll_bb(x["n0"], x["N"], p[0], p[1])
            sizes = x["sizes"] if (x["kbqa"] and self.empty_table) else (x["sizes_e"] if x["kbqa"] else x["sizes"])
            part = p[2]
        if self.urn and x["L"]:
            ll += ll_urn(sizes, part, x["L"])
        else:
            ll += ll_crp(sizes, part)
        return ll


def _key(x):
    return (x["N"], x["n0"], x["e"], x["r"], tuple(x["sizes"]), tuple(x["sizes_e"]), x["L"], x["kbqa"])


def fit_class(xs, spec, kbqa, seed=0, iters=60, restarts=3):
    """EM for a J-component mixture on the class's questions (identical vote patterns merged with counts).
    -> (log weights, [log-params per component])."""
    P = spec.n_comp_params(kbqa)
    groups = {}
    for x in xs:
        groups.setdefault(_key(x), [x, 0])[1] += 1
    ux = [g[0] for g in groups.values()]
    cnt = np.array([g[1] for g in groups.values()], float)
    n = len(ux)
    best = None
    rng = np.random.default_rng(seed)
    for rs in range(restarts if spec.J > 1 else 1):
        if spec.J == 1:
            R = np.ones((n, 1))
        else:
            # init: split by abstention share (IDK + empty) with noise
            idk = np.array([(x["n0"] + x["e"]) / max(x["N"], 1) for x in ux])
            R = np.stack([idk, 1 - idk], 1) + rng.uniform(0, 0.3 + 0.3 * rs, (n, 2))
            R /= R.sum(1, keepdims=True)
        params = [np.zeros(P) for _ in range(spec.J)]
        prev = -np.inf
        for it in range(iters if spec.J > 1 else 1):
            for j in range(spec.J):
                w = cnt * R[:, j]
                keep = w > 1e-9
                xx, ww = [x for x, k in zip(ux, keep) if k], w[keep]
                f = lambda p: -float(np.dot(ww, [spec.comp_ll(x, p) for x in xx]))
                params[j] = minimize(f, params[j], method="L-BFGS-B", bounds=[(-7, 7)] * P).x
            logw = np.log((cnt[:, None] * R).sum(0) / cnt.sum() + 1e-12)
            lls = np.array([[spec.comp_ll(x, params[j]) for j in range(spec.J)] for x in ux]) + logw
            tot = np.logaddexp.reduce(lls, 1)
            R = np.exp(lls - tot[:, None])
            ll = float(np.dot(cnt, tot))
            if ll - prev < 1e-5:
                break
            prev = ll
        if best is None or ll > best[2]:
            best = (logw, params, ll)
    return best[0], best[1]


def class_ll(x, model, spec):
    logw, params = model
    return float(np.logaddexp.reduce([logw[j] + spec.comp_ll(x, params[j]) for j in range(spec.J)]))


class ReservedTables:
    def __init__(self, spec):
        self.spec = spec

    def fit(self, xs, ys):
        kb = xs[0]["kbqa"]
        self.mA = fit_class([x for x, y in zip(xs, ys) if not y], self.spec, kb)
        self.mU = fit_class([x for x, y in zip(xs, ys) if y], self.spec, kb)
        return self

    def score(self, xs):
        return np.array([class_ll(x, self.mU, self.spec) - class_ll(x, self.mA, self.spec) for x in xs])


# ---------- decision + Overall F1 (same definition as the dashboard) ----------
def cells(xs, ys, abstain):
    """-> counts (ac, aw, au, ua, uu). Answer = largest real cluster; none -> abstain."""
    c = np.zeros(5)
    for x, y, ab in zip(xs, ys, abstain):
        ab = ab or x["r"] == 0
        if not y:
            c[2 if ab else (0 if x["top_ok"] else 1)] += 1
        else:
            c[4 if ab else 3] += 1
    return c


def f1_from(c):
    ac, aw, au, ua, uu = c
    A, U = ac + aw + au, ua + uu
    pa = ac / (ac + aw + ua) if ac + aw + ua else 0
    ra = ac / A if A else 0
    pu = uu / (uu + au) if uu + au else 0
    ru = uu / U if U else 0
    f = lambda p, r: 2 * p * r / (p + r) if p + r else 0
    return dict(f1=(f(pa, ra) + f(pu, ru)) / 2, A_acc=ra, U_acc=ru, answered=(ac + aw + ua) / (A + U))


def tune_tau(scores, xs, ys):
    """tau maximising Overall F1 on dev; never-answer excluded; ties -> middle of the tied list."""
    v = np.unique(scores)
    taus = np.concatenate([[v[0] - 1], (v[:-1] + v[1:]) / 2, [v[-1] + 1]])
    res = []
    for t in taus:
        ab = scores > t
        c = cells(xs, ys, ab)
        res.append(-1 if c[0] + c[1] + c[3] == 0 else f1_from(c)["f1"])
    res = np.array(res)
    good = taus[res >= res.max() - 1e-12]
    return float(good[len(good) // 2])
